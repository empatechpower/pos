// Turns the prototype's own <style> blocks (proto-reference/index.html) into src/proto/proto.css, scoped under ".proto".
//   node proto-reference/make-css.mjs
// - the prototype's page-level rules (:root, html, body, *) apply to the ".proto" wrapper instead;
// - every other selector is prefixed with ".proto ";
// - "rem" becomes calc(N * var(--u)): the prototype sets the root font size to 16px x the text-size choice, and --u is that, so the
//   Compact / Standard / Large / Extra large setting scales it exactly as in the prototype (media-query rems are left alone);
// - @media print is dropped (it hides everything but the dialog).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, "index.html"), "utf8");
const css = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");

const scope = (sel) =>
  sel.split(",").map((s) => s.trim()).filter(Boolean).map((s) => {
    if (/^(:root|html|body)$/.test(s)) return ".proto";
    if (s === "*") return ".proto, .proto *";
    if (/^(:root|html|body)\b/.test(s)) return s.replace(/^(:root|html|body)/, ".proto");
    return `.proto ${s}`;
  }).join(", ");

const root = postcss.parse(css);
root.walkAtRules("media", (r) => { if (/print/.test(r.params)) r.remove(); });
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  rule.selector = scope(rule.selector);
});
root.walkDecls((d) => {
  if (d.prop === "font-size" && d.parent?.selector === ".proto") { d.remove(); return; } // the wrapper's size comes from --u
  d.value = d.value.replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => (Number(n) === 0 ? "0" : `calc(${n} * var(--u))`));
});
const out = `/* GENERATED by proto-reference/make-css.mjs from the prototype's own stylesheet. Do not edit by hand: change the script, or the screens' markup. */\n.proto { --u: calc(16px * var(--t-scale, 1.2)); font-size: var(--u); min-height: 100%; }\n` + root.toString();
writeFileSync(join(here, "../src/proto/proto.css"), out);
console.log("proto.css:", out.length, "bytes");
