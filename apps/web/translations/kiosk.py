#!/usr/bin/env python3
"""
The kiosk's translations.

  translations/phrases.json   the English phrases, once, in a fixed order (a phrase's position is its id)
  translations/kiosk/<code>.txt   one file per language, lines of  id|translation   (a missing line = shown in English)

  python3 translations/kiosk.py build                 writes src/kioskPhrases.ts from the files above
  python3 translations/kiosk.py review-import FILE    reads a reviewer's spreadsheet (column D of each language sheet), puts
                                                      their corrections into the language files, then builds

Never change the order of phrases.json: ids are positions. To add a phrase, append it at the end.
"""
import glob, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
EN = json.load(open(os.path.join(HERE, "phrases.json"), encoding="utf-8"))
OUT = os.path.join(HERE, "..", "src", "kioskPhrases.ts")


def read(code):
    m = {}
    for line in open(os.path.join(HERE, "kiosk", code + ".txt"), encoding="utf-8").read().splitlines():
        if line.strip():
            i, _, t = line.partition("|")
            m[int(i)] = t.strip()
    return m


def check(code, m):
    bad = []
    for i, t in m.items():
        if not 0 <= i < len(EN):
            bad.append((code, i, "no such phrase"))
            continue
        for ph in re.findall(r"\{[a-z]+\}", EN[i]):
            if ph not in t:
                bad.append((code, i, "missing " + ph))
    return bad


def build():
    out = [
        "/** DRAFT translations of the kiosk's screens (machine-drafted; being reviewed by speakers of each language).",
        " *  GENERATED by translations/kiosk.py from translations/kiosk/*.txt: edit those, not this file.",
        " *  KIOSK_EN lists the English phrases once; each language is a sparse list by position. Missing = shown in English. */",
        "export const KIOSK_EN: string[] = " + json.dumps(EN, ensure_ascii=False) + ";",
        "export const KIOSK_TR: Record<string, Record<number, string>> = {",
    ]
    problems = []
    for f in sorted(glob.glob(os.path.join(HERE, "kiosk", "*.txt"))):
        code = os.path.basename(f)[:-4]
        m = read(code)
        problems += check(code, m)
        out.append(" " + json.dumps(code) + ": {" + ",".join(f"{i}:{json.dumps(t, ensure_ascii=False)}" for i, t in sorted(m.items())) + "},")
    out.append("};")
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("built", OUT)
    if problems:
        print("PROBLEMS:", problems)
        sys.exit(1)


def review_import(path):
    from openpyxl import load_workbook  # pip install openpyxl

    wb = load_workbook(path, data_only=True)
    changed = 0
    for ws in wb.worksheets:
        code = ws.title
        if not os.path.exists(os.path.join(HERE, "kiosk", code + ".txt")):
            continue
        m = read(code)
        for row in ws.iter_rows(min_row=2, values_only=True):
            i, _en, _draft, fixed = (list(row) + [None] * 4)[:4]
            if isinstance(i, int) and isinstance(fixed, str) and fixed.strip() and fixed.strip() != m.get(i):
                m[i] = fixed.strip()
                changed += 1
        open(os.path.join(HERE, "kiosk", code + ".txt"), "w", encoding="utf-8").write("\n".join(f"{i}|{t}" for i, t in sorted(m.items())) + "\n")
    print("corrections applied:", changed)
    build()


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "build":
        build()
    elif len(sys.argv) == 3 and sys.argv[1] == "review-import":
        review_import(sys.argv[2])
    else:
        print(__doc__)
